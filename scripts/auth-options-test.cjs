const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { build } = require('esbuild');
const tick = () => new Promise(resolve => setTimeout(resolve, 0));

(async () => {
  const { createAuthController } = await import('../src/auth/controller.js');
  const { EMPTY_ACCOUNT } = await import('../src/auth/policy.js');
  const { NATIVE_AUTH_CALLBACK, googleOAuthOptions, readNativeAuthCallback, trustedGoogleAuthorizeUrl, safeAuthReturnPath, createNativeAuthCallbackHandler } = await import('../src/auth/oauth.js');
  assert.equal(googleOAuthOptions({ native: true }).redirectTo, NATIVE_AUTH_CALLBACK);
  assert.equal(googleOAuthOptions({ native: true }).skipBrowserRedirect, true);
  assert.equal(googleOAuthOptions({ origin: 'https://app.example', returnPath: '/seller/service/dashboard' }).redirectTo, 'https://app.example/seller/service/dashboard');
  assert.equal(safeAuthReturnPath('https://another-site.example'), '/user/home');
  assert.equal(safeAuthReturnPath('//another-site.example'), '/user/home');
  assert.deepEqual(readNativeAuthCallback(`${NATIVE_AUTH_CALLBACK}?code=valid-code`), { code: 'valid-code' });
  for (const invalid of ['https://another-site.example/auth/callback?code=a', 'com.eazily.app://other/callback?code=a', 'com.eazily.app://auth/wrong?code=a', 'com.eazily.app://user@auth/callback?code=a']) assert.equal(readNativeAuthCallback(invalid), null);
  assert.ok(readNativeAuthCallback(`${NATIVE_AUTH_CALLBACK}?error=access_denied`).error);
  assert.ok(readNativeAuthCallback(NATIVE_AUTH_CALLBACK).error);
  assert.equal(trustedGoogleAuthorizeUrl('https://project.supabase.co/auth/v1/authorize?provider=google', 'https://project.supabase.co'), true);
  assert.equal(trustedGoogleAuthorizeUrl('https://another-site.example/auth/v1/authorize?provider=google', 'https://project.supabase.co'), false);
  assert.equal(trustedGoogleAuthorizeUrl('http://project.supabase.co/auth/v1/authorize?provider=google', 'https://project.supabase.co'), false);
  let exchanges = 0, returns = [], closes = 0, errors = [];
  const handler = createNativeAuthCallbackHandler({ exchangeCode: async () => { exchanges++; await tick(); return true; }, readReturnPath: () => '/seller/service/dashboard', onSuccess: p => returns.push(p), onError: e => errors.push(e), closeBrowser: async () => { closes++; } });
  await Promise.all([handler(`${NATIVE_AUTH_CALLBACK}?code=once`), handler(`${NATIVE_AUTH_CALLBACK}?code=once`)]);
  await handler(`${NATIVE_AUTH_CALLBACK}?code=once`);
  assert.equal(exchanges, 1, 'Duplicate cold/warm callback delivery exchanges a PKCE code once.');
  assert.deepEqual(returns, ['/seller/service/dashboard']);
  assert.equal(closes, 1);
  await handler(`${NATIVE_AUTH_CALLBACK}?error=access_denied&error_description=private-provider-details`);
  assert.equal(exchanges, 1);
  assert.equal(errors.length, 1);
  assert.doesNotMatch(errors[0], /private-provider-details/);

  let account = EMPTY_ACCOUNT, launches = 0, codeExchanges = 0, exchangeError = null;
  const verified = { ...EMPTY_ACCOUNT, user: { id: 'google-user' }, profile: { id: 'google-user', full_name: 'Asha', account_status: 'active' } };
  const client = { auth: { onAuthStateChange: () => ({ data: { subscription: { unsubscribe() {} } } }), signInWithOAuth: async () => ({ error: null }), exchangeCodeForSession: async () => { codeExchanges++; if (!exchangeError) account = verified; return { error: exchangeError }; }, signOut: async () => ({ error: null }) } };
  const controller = createAuthController({ client, loadAccount: async () => account, googleSignIn: async () => { launches++; }, loadAuthSettings: async () => ({ google: true, email: true, signup: true }) });
  const stop = controller.start(); await tick();
  assert.equal(await controller.signInWithGoogle(), true);
  assert.equal(controller.getSnapshot().oauthPending, true);
  assert.equal(await controller.signInWithGoogle(), false, 'Repeated taps do not start a second Google flow.');
  assert.equal(launches, 1);
  controller.cancelGoogleSignIn();
  assert.equal(controller.getSnapshot().oauthPending, false);
  assert.equal(await controller.signInWithGoogle(), true);
  exchangeError = { code: 'bad_code_verifier' };
  assert.equal(await controller.completeGoogleSignIn('bad-code'), false);
  assert.equal(controller.getSnapshot().account.user, null);
  assert.equal(controller.getSnapshot().oauthPending, false, 'A failed callback never leaves sign-in controls permanently busy.');
  assert.doesNotMatch(controller.getSnapshot().error, /bad_code_verifier/);
  exchangeError = null;
  assert.equal(await controller.completeGoogleSignIn('valid-code'), true);
  assert.equal(controller.getSnapshot().account.user.id, 'google-user');
  await controller.logout();
  const before = codeExchanges;
  assert.equal(await controller.completeGoogleSignIn('late-code'), false, 'A late callback cannot reverse logout.');
  assert.equal(codeExchanges, before);
  assert.equal(await controller.signInWithGoogle(), true, 'A new explicit Google login works after sign-out.');
  stop();

  const out = path.resolve('.tmp/auth-options-renderer.cjs');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  await build({ stdin: { contents: `import React from 'react'; import {renderToStaticMarkup} from 'react-dom/server'; import {GoogleEmailSignIn} from './src/auth/AuthScreen.jsx'; export function render(auth){return renderToStaticMarkup(React.createElement(GoogleEmailSignIn,{auth,onBack(){},onContinue(){}}));}`, resolveDir: path.resolve('.') }, outfile: out, bundle: true, platform: 'node', format: 'cjs', jsx: 'automatic', external: ['react', 'react-dom', 'react-dom/server'], loader: { '.css': 'empty' }, define: { 'import.meta.env': '{}' }, logLevel: 'silent' });
  const { render } = require(out);
  const base = { status: 'signed_out', providers: { google: true, email: true, signup: true }, controller: {}, resendAt: 0 };
  const enabled = render(base);
  assert.match(enabled, /Continue with Google/); assert.match(enabled, /Send email code/);
  assert.match(enabled, /id="auth-email" type="email"/);
  assert.doesNotMatch(enabled, /type="tel"|SMS|mobile number/, 'No mobile authentication controls are rendered.');
  assert.doesNotMatch(enabled.match(/<button[^>]+class="auth-choice-google"[^>]*>/)[0], /disabled/);
  const disabled = render({ ...base, providers: { google: false, email: false } });
  assert.match(disabled, /Continue with Google/); assert.match(disabled, /Send email code/);
  assert.match(disabled.match(/<button[^>]+class="auth-choice-google"[^>]*>/)[0], /disabled/);
  assert.match(disabled, /Google sign-in is temporarily unavailable/);
  assert.match(disabled, /Email sign-in is temporarily unavailable/);
  console.log('PASS: both rendered sign-in choices, disabled-provider states, PKCE callback validation/deduplication, native return paths, Google launch/cancellation/errors, and logout isolation. No live login or email delivery was attempted.');
})().catch(error => { console.error(error); process.exitCode = 1; });

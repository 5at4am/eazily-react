# Build the debug Android APK.
#
# Picks a JDK 21 or newer (Capacitor's generated capacitor-android module compiles
# at source level 21, so JDK 17 fails with "invalid source release: 21"), points
# Gradle at the Android SDK, builds app-debug.apk and copies it next to the
# project folder so it is easy to install.
#
#   npm.cmd run android:debug
$ErrorActionPreference = 'Stop'
$projectRoot = Resolve-Path (Join-Path $PSScriptRoot '..')
$androidRoot = Join-Path $projectRoot 'android'
$requiredPlatform = 'android-36'

function Get-JdkVersion([string]$path) {
  if (-not $path -or -not (Test-Path -LiteralPath $path)) { return 0 }
  $release = Join-Path $path 'release'
  if (Test-Path -LiteralPath $release) {
    $match = Select-String -Path $release -Pattern '^JAVA_VERSION="?(\d+)' | Select-Object -First 1
    if ($match) { return [int]$match.Matches[0].Groups[1].Value }
  }
  if (Test-Path -LiteralPath (Join-Path $path 'bin\java.exe')) {
    $version = & (Join-Path $path 'bin\java.exe') -version 2>&1 | Select-Object -First 1
    if ($version -match '"(\d+)') { return [int]$Matches[1] }
  }
  return 0
}

$jdkRoots = @(
  $env:JAVA_HOME,
  (Join-Path $env:ProgramFiles 'Microsoft'),
  (Join-Path $env:ProgramFiles 'Java'),
  (Join-Path ${env:ProgramFiles(x86)} 'Microsoft'),
  (Join-Path $env:ProgramFiles 'Eclipse Adoptium'),
  (Join-Path $env:ProgramFiles 'Zulu'),
  (Join-Path $env:ProgramFiles 'Amazon Corretto'),
  (Join-Path $env:LOCALAPPDATA 'Programs\Microsoft'),
  (Join-Path $env:ProgramFiles 'Android\Android Studio\jbr')
) | Where-Object { $_ }

$candidates = @()
foreach ($root in $jdkRoots) {
  if (Test-Path -LiteralPath (Join-Path $root 'bin\java.exe')) { $candidates += $root }
  if (Test-Path -LiteralPath $root) {
    foreach ($child in Get-ChildItem -LiteralPath $root -Directory -ErrorAction SilentlyContinue) {
      if ($child.Name -match '^(jdk|jre|temurin|zulu|corretto)' -and (Test-Path -LiteralPath (Join-Path $child.FullName 'bin\java.exe'))) { $candidates += $child.FullName }
    }
  }
}
$candidates = $candidates | Select-Object -Unique
$jdk = $candidates | ForEach-Object { [pscustomobject]@{ Path = $_; Version = (Get-JdkVersion $_) } } |
  Where-Object { $_.Version -ge 21 } | Sort-Object Version -Descending | Select-Object -First 1
if (-not $jdk) {
  throw 'No JDK 21 or newer was found. Capacitor compiles at source level 21. Install JDK 21 or 24 and rerun.'
}
$env:JAVA_HOME = $jdk.Path
$env:PATH = "$env:JAVA_HOME\bin;$env:PATH"
Write-Host "Using JDK $($jdk.Version) at $env:JAVA_HOME"

$sdk = $env:ANDROID_HOME
if (-not $sdk) { $sdk = $env:ANDROID_SDK_ROOT }
if (-not $sdk -or -not (Test-Path -LiteralPath $sdk)) {
  $sdk = Join-Path $env:LOCALAPPDATA 'Android\Sdk'
}
if (-not (Test-Path -LiteralPath $sdk)) { throw 'The Android SDK was not found. Set ANDROID_HOME.' }
if (-not (Test-Path -LiteralPath (Join-Path $sdk "platforms\$requiredPlatform"))) {
  throw "SDK Platform $requiredPlatform is missing. Install it with the Android SDK manager, then rerun."
}
Write-Host "Using Android SDK at $sdk"

$localProperties = Join-Path $androidRoot 'local.properties'
$sdkDir = "sdk.dir=$($sdk -replace '\\','/')"
if (-not (Test-Path -LiteralPath $localProperties) -or -not (Select-String -Path $localProperties -Pattern '^sdk.dir=' -Quiet)) {
  Set-Content -LiteralPath $localProperties -Value "## Generated by scripts/android-build.ps1. Do not commit.`n$sdkDir" -NoNewline
}

Push-Location $androidRoot
try {
  & (Join-Path $androidRoot 'gradlew.bat') assembleDebug --no-daemon --console=plain
  if ($LASTEXITCODE -ne 0) { throw "Gradle build failed with exit code $LASTEXITCODE" }
} finally {
  Pop-Location
}

$apk = Join-Path $androidRoot 'app\build\outputs\apk\debug\app-debug.apk'
if (-not (Test-Path -LiteralPath $apk)) { throw "The build reported success but $apk is missing." }
$destination = Join-Path (Split-Path $projectRoot -Parent) 'Eazily-debug.apk'
Copy-Item -LiteralPath $apk -Destination $destination -Force
Write-Host "APK: $destination ($([math]::Round((Get-Item $destination).Length / 1MB, 2)) MB)"
